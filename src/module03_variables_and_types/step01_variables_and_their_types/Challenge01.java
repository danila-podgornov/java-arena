package module03_variables_and_types.step01_variables_and_their_types;

public class Challenge01 {
    /**
     * Fill in the three values so the program prints exactly {@code Mo ran 3 laps of 2.5 km}.
     * Expected output
     * {@code Mo ran 3 laps of 2.5 km}
     */
    public static void main(String[] args) {
        int laps = 3;
        double distance = 2.5;
        String runner = "Mo";
        System.out.println(runner + " ran " + laps + " laps of " + distance + " km");
    }
}
